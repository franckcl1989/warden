def _ts_literal(value: object) -> str:
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, dict):
        items = ", ".join(f"{_ts_literal(k)}: {_ts_literal(v)}" for k, v in value.items())
        return "{" + items + "}"
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_ts_literal(item) for item in value) + "]"
    msg = f"unsupported literal type: {type(value)}"
    raise TypeError(msg)


def _emit_frontend(contracts: ContractSet) -> str:
    device_types = sorted({r.device_type for r in contracts.requirements.values()})
    metric_keys = sorted(contracts.metric_definitions)
    event_keys = sorted(contracts.event_definitions)
    capability_keys = sorted(contracts.requirements_by_capability)
    error_codes = sorted(contracts.stable_errors)
    operation_keys = sorted(contracts.operation_profiles)
    enum_sets = contracts.enum_sets
    lines = [
        "// GENERATED by app.tools.codegen from contracts/ - DO NOT EDIT.",
        "// eslint-disable",
        "",
        f"export const PRODUCT_VERSION = {_ts_literal(contracts.product_version)};",
        "",
        "export const DEVICE_TYPES = " + _ts_literal(device_types) + " as const;",
        "export type DeviceType = (typeof DEVICE_TYPES)[number];",
        "",
        "export const METRIC_KEYS = " + _ts_literal(metric_keys) + " as const;",
        "export type MetricKey = (typeof METRIC_KEYS)[number];",
        "",
        "export const EVENT_KEYS = " + _ts_literal(event_keys) + " as const;",
        "export type EventKey = (typeof EVENT_KEYS)[number];",
        "",
        "export const CAPABILITY_KEYS = " + _ts_literal(capability_keys) + " as const;",
        "export type CapabilityKey = (typeof CAPABILITY_KEYS)[number];",
        "",
        "export const OPERATION_PROFILE_IDS = " + _ts_literal(operation_keys) + " as const;",
        "export type OperationProfileId = (typeof OPERATION_PROFILE_IDS)[number];",
        "",
        "export const ERROR_CODES = " + _ts_literal(error_codes) + " as const;",
        "export type ErrorCode = (typeof ERROR_CODES)[number];",
        "",
        "export const METRIC_META: Record<string, { valueType: string; unit: string | null; scope: string; series: string; alertPolicy: string }> = {",  # noqa: E501
    ]
    for key in metric_keys:
        metric = contracts.metric_definitions[key]
        lines.append(
            f"  {key!r}: {{ valueType: {metric.value_type!r}, unit: {_ts_literal(metric.unit)}, "
            f"scope: {metric.scope!r}, series: {metric.series!r}, alertPolicy: {metric.alert_policy!r} }},"
        )
    lines += ["};", "", "export const ENUM_SETS: Record<string, readonly string[]> = {"]
    for name in sorted(enum_sets):
        lines.append(f"  {name!r}: " + _ts_literal(list(enum_sets[name])) + ",")
    lines += ["};", "", "export const REQUIREMENTS: Record<string, { deviceType: DeviceType; kind: 'monitoring' | 'operation'; title: string }> = {"]  # noqa: E501
    for req_id in sorted(contracts.requirements):
        requirement = contracts.requirements[req_id]
        lines.append(
            f"  {req_id!r}: {{ deviceType: {requirement.device_type!r}, kind: {requirement.kind!r}, title: {requirement.title!r} }},",  # noqa: E501
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


def run() -> None:
    contracts = load_contracts()
    validate_contracts(contracts)

    BACKEND_GENERATED.mkdir(parents=True, exist_ok=True)
    FRONTEND_GENERATED.mkdir(parents=True, exist_ok=True)

    emitters: dict[str, str] = {
        "metrics.py": _emit_metrics(contracts),
        "events.py": _emit_events(contracts),
        "operations.py": _emit_operations(contracts),
        "alerts.py": _emit_alerts(contracts),
        "errors.py": _emit_errors(contracts),
        "capabilities.py": _emit_capabilities(contracts),
        "http_api.py": _emit_http_api(contracts),
        "hardware_targets.py": _emit_hardware_targets(contracts),
    }
    for filename, content in emitters.items():
        (BACKEND_GENERATED / filename).write_text(content, encoding="utf-8")

    (FRONTEND_GENERATED / "contracts.ts").write_text(_emit_frontend(contracts), encoding="utf-8")
    print("Codegen complete.")


if __name__ == "__main__":
    run()
