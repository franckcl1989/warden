"""Codegen: regenerate backend registries and frontend contract constants.

Outputs are committed to the repository and must never be edited by hand.
CI runs this tool and fails on drift. Generated files can be deleted and
rebuilt entirely from contracts/.
"""

from __future__ import annotations

import json
from pathlib import Path

from app.contracts.loader import load_contracts
from app.contracts.validation import validate_contracts
from app.domain.contracts import ContractSet

REPO_ROOT = Path(__file__).resolve().parents[3]
BACKEND_GENERATED = REPO_ROOT / "backend" / "app" / "generated"
FRONTEND_GENERATED = REPO_ROOT / "frontend" / "src" / "api" / "generated"

GENERATED_HEADER = "# GENERATED by app.tools.codegen from contracts/ - DO NOT EDIT.\n"


def _py_literal(value: object) -> str:
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, bool):
        return "True" if value else "False"
    if value is None:
        return "None"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, dict):
        items = ", ".join(f"{_py_literal(k)}: {_py_literal(v)}" for k, v in value.items())
        return "{" + items + "}"
    if isinstance(value, (list, tuple)):
        items = ", ".join(_py_literal(item) for item in value)
        return "(" + items + ("," if len(value) == 1 else "") + ")"
    msg = f"unsupported literal type: {type(value)}"
    raise TypeError(msg)


def _emit_metrics(contracts: ContractSet) -> str:
    lines = [
        GENERATED_HEADER,
        '"""Metric definitions and enum sets (contracts/metrics.json)."""',
        "",
        "from app.domain.contracts import MetricDefinition",
        "",
        "ENUM_SETS: dict[str, tuple[str, ...]] = {",
    ]
    for name in sorted(contracts.enum_sets):
        lines.append(f"    {name!r}: {_py_literal(contracts.enum_sets[name])},")
    lines += ["}", "", "METRIC_DEFINITIONS: dict[str, MetricDefinition] = {"]
    for key in sorted(contracts.metric_definitions):
        metric = contracts.metric_definitions[key]
        lines.append(
            f"    {key!r}: MetricDefinition("
            f"key={metric.key!r}, value_type={metric.value_type!r}, enum_set={metric.enum_set!r}, "
            f"unit={metric.unit!r}, scope={metric.scope!r}, series={metric.series!r}, "
            f"alert_policy={metric.alert_policy!r}, range={_py_literal(metric.range)}),"
        )
    lines.append("}")
    return "\n".join(lines) + "\n"


